def _fix(name):
    if name == "gr":
        # key 16 is ;/: — shift is colon, qt stays semicolon
        letters = []
        for kc, ch in zip(_LETTER_KC, _LAYOUTS["gr"][0]):
            lo = ord(ch)
            if kc == 16:
                letters.append((16, 0x3B, 0x3A, 0x3B))
                continue
            up = ord(ch.upper()) if len(ch.upper()) == 1 else lo
            letters.append((kc, lo, up, up))
        return letters, list(_LAYOUTS["gr"][1])

    if name == "tr":
        # keep capital I (U+0049) on key 23 shift, not İ
        letters = _letters(_LAYOUTS["tr"][0])
        letters = [
            (23, 0x0131, 0x49, 0x49) if t[0] == 23 else t
            for t in letters
        ]
        return letters, list(_LAYOUTS["tr"][1])

    entry = _LAYOUTS[name]
    if isinstance(entry, str):
        return _fix(entry)
    base, punct = entry
    return _letters(base), list(punct)


# Public registry (callables for back-compat with anything inspecting LAYOUTS)
LAYOUTS = {name: (lambda n=name: _fix(n)) for name in _LAYOUTS}


def get_layout_mappings(layout_name):
    if layout_name not in _LAYOUTS:
        raise ValueError(
            f"Unknown layout: {layout_name}. Available: {list(_LAYOUTS)}"
        )
    return _fix(layout_name)
